"""공고 본문에 남은 개인정보를 한 번 더 지운다.

왜 또 하는가
------------
팀원 수집기(`body_sanitize.py`)가 이미 마스킹을 했고 1,980건 중 730건에서
발동했다. 그런데 배포 직전 검사에서 **전화번호 24건이 그대로 남아 있었다.**

    ( 010 - 2273 - 1603 )        하이픈 양쪽 공백
    010- 4767 - 9817             구분자 폭이 들쭉날쭉
    051 - 464 - 1995             지역번호도 같은 이유
    070-4833-2733                070 대역이 규칙에 없음

원인은 구분자 폭이다. 보통 `[-.\\s]?` 처럼 구분자를 0~1글자로 잡는데
실제 공고는 ` - ` 처럼 3글자를 쓴다. 그래서 구분자를 0~4글자로 넓혔다.

담당자 실명도 남아 있었다(`권주은팀장`, `정현희 부장` 등). 직함 앞의 토큰이
한국 성씨로 시작하는 2~3음절이면 이름으로 보고 직함까지 함께 지운다.
"채용 담당자" 처럼 일반어가 함께 지워지는 것은 감수한다 —
이 본문은 근로조건 진단에만 쓰므로 담당자 이름이 필요 없고,
덜 지워서 실명이 새는 쪽이 훨씬 나쁘다.

지우지 않는 것
--------------
근무시간·금액·날짜·기간은 건드리지 않는다. 진단의 근거이기 때문이다.
아래 자체 테스트가 그것을 확인한다.

    python body_remask.py        # 테스트만 실행
"""
from __future__ import annotations

import re
import sys

# 구분자를 넓게 잡는다. 이게 이 파일의 핵심이다.
SEP = r"[\s\-.·)(]{0,4}"

# 성씨 — 빈도 상위. 이름 판별에만 쓰므로 완전할 필요는 없다.
SURNAME = (
    "김이박최정강조윤장임한오서신권황안송류전홍고문양손배백허유남심노정하곽성차주우구"
    "민류나진지엄채원천방공강현함변염양변여추도소석선설마길연위표명기반왕금옥육인맹제"
    "모장남탁국여진어은편용"
)

TITLE = ("팀장|과장|부장|차장|대리|실장|점장|사장|대표|매니저|담당자|주임|이사|소장|원장")

RULES: list[tuple[str, str]] = [
    # ── 전화 ─────────────────────────────────────────────────────────
    # 휴대폰. 010~019
    (rf"01[016789]{SEP}\d{{3,4}}{SEP}\d{{4}}", "[전화번호]"),
    # 인터넷전화·안심번호
    (rf"\b0(?:70|50\d?){SEP}\d{{3,4}}{SEP}\d{{4}}\b", "[전화번호]"),
    # 지역번호. 괄호 표기 02) 1234-5678 도 잡는다
    (rf"\b0(?:2|3[1-3]|4[1-4]|5[1-5]|6[1-4])(?:\){SEP}|{SEP})\d{{3,4}}{SEP}\d{{4}}\b",
     "[전화번호]"),
    # 대표번호 15xx/16xx/18xx
    (rf"\b1[5-9]\d{{2}}{SEP}\d{{4}}\b", "[전화번호]"),
    # ── 이메일 ───────────────────────────────────────────────────────
    # 공백·한글 우회(골뱅이, [at])까지
    (r"[\w.+\-]+\s?(?:@|＠|골뱅이|\[at\]|\(at\))\s?[\w\-]+(?:\s?\.\s?[\w\-]+)+",
     "[이메일]"),
    # ── 메신저·SNS ───────────────────────────────────────────────────
    (r"(?:open\.kakao\.com|pf\.kakao\.com|kakao\.com)/\S+", "[링크]"),
    (r"(?:instagram\.com|blog\.naver\.com|cafe\.naver\.com|band\.us)/\S+", "[링크]"),
    # '카톡ID: xxx' / '카카오톡 아이디 xxx' 형태의 아이디
    (r"(카톡|카카오톡)\s?(아이디|ID|id)\s?[:：]?\s?[\w.\-]{3,}", r"\1 [아이디]"),
    # ── 사업자등록번호 ───────────────────────────────────────────────
    (r"\b\d{3}\s?-\s?\d{2}\s?-\s?\d{5}\b", "[사업자번호]"),
    # ── 담당자 실명 ──────────────────────────────────────────────────
    (rf"[{SURNAME}][가-힣]{{1,2}}\s?(?:{TITLE})", "[담당자]"),
]

COMPILED = [(re.compile(p), r) for p, r in RULES]


def remask(text: str) -> str:
    """본문 하나를 마스킹한다. 문자열이 아니면 빈 문자열."""
    if not isinstance(text, str) or not text:
        return "" if not isinstance(text, str) else text
    for pat, rep in COMPILED:
        text = pat.sub(rep, text)
    return text


# ─────────────────────────────────────────────────────────────────────────────
# 자체 테스트 — 지울 것은 지우고, 남길 것은 남기는지
# ─────────────────────────────────────────────────────────────────────────────

MUST_MASK = [
    # 실제 수집분에서 새어 나온 형태들
    ("담당자 : 010 - 2128 - 2226", "010"),
    ("빠르게 문자로 지원하기 010- 4767 - 9817", "4767"),
    ("( 010 - 2273 - 1603 )", "2273"),
    ("연락처 : 051 - 464 - 1995", "464"),
    ("팩스 접수 : 070-4833-2733", "4833"),
    ("연락처 070-5029-3011", "5029"),
    ("문의 01012345678", "0101234"),
    ("전화 02)123-4567", "123-4567"),
    ("대표번호 1588-1234", "1588"),
    ("메일 hong@naver.com 으로", "@naver"),
    ("메일 hong @ naver . com", "naver"),
    ("사업자등록번호 123-45-67890", "123-45-67890"),
    ("오픈채팅 open.kakao.com/o/abc123", "abc123"),
    ("카톡ID: mystore77", "mystore77"),
    ("권주은팀장", "권주은"),
    ("정현희 부장 연락주세요", "정현희"),
    ("이슬기 팀장", "이슬기"),
    ("장용희 주임", "장용희"),
]

MUST_KEEP = [
    # 근로조건 — 하나도 훼손되면 안 된다
    ("근무시간 09:00~18:00 (휴게 60분)", ["09:00", "18:00", "60분"]),
    ("시급 10,320원 / 월급 2,200,000원", ["10,320", "2,200,000"]),
    ("주 5일 근무, 주휴수당 별도 지급", ["5일", "주휴수당"]),
    ("모집기간 2026-08-01 ~ 2026-08-31", ["2026-08-01", "2026-08-31"]),
    ("연봉 3,600만원 (수습 3개월 90%)", ["3,600", "3개월", "90%"]),
    ("11:00~15:00 중 4시간, 시간협의", ["11:00", "15:00", "4시간"]),
    ("경력 2년 이상, 4대보험 가입", ["2년", "4대보험"]),
    ("일급 150,000원 08:00~18:00", ["150,000", "08:00"]),
    ("2026년 최저임금 10,320원", ["2026", "10,320"]),
    ("교통비 100,000원, 식대 10만원", ["100,000", "10만원"]),
]


def selftest() -> int:
    bad = 0
    for src, leak in MUST_MASK:
        got = remask(src)
        if leak in got:
            print(f"  ✗ 안 지워짐: {src!r} -> {got!r}")
            bad += 1
    for src, keeps in MUST_KEEP:
        got = remask(src)
        for k in keeps:
            if k not in got:
                print(f"  ✗ 지워지면 안 되는 값 손실: {k!r} in {src!r} -> {got!r}")
                bad += 1
    n = len(MUST_MASK) + sum(len(k) for _, k in MUST_KEEP)
    print(f"자체 테스트 {n - bad}/{n} 통과"
          f"  (마스킹 {len(MUST_MASK)}건 · 보존 {sum(len(k) for _, k in MUST_KEEP)}건)")
    return bad


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(1 if selftest() else 0)
