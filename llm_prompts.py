class LabelJudgement(BaseModel):
    """라벨 1종의 판정 결과."""

    flag: Literal[0, 1] = Field(
        description="1=구직자가 지원 전에 이 조건을 알 수 없음(확인 필요). 0=문제 없음."
    )
    evidence: str = Field(
        description=(
            "flag=1 의 근거가 되는 본문 구절을 원문 표기 그대로 인용(최대 60자). "
            "본문에 관련 서술이 아예 없어서 1인 경우, 그리고 flag=0 인 경우에는 빈 문자열."
        )
    )


class Detection(BaseModel):
    """공고 1건의 근로조건 진단 결과."""

    status: Literal["진단완료", "본문없음"] = Field(
        description="본문이 비었거나 30자 미만이면 '본문없음'. 그 경우 모든 flag 를 0 으로 둔다."
    )
    임금구성_불명확: LabelJudgement
    실근로시간_미기재: LabelJudgement
